#!/usr/bin/env python3

import hashlib
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..", "..")
sys.path.insert(0, HERE)

import Gw2TransportCipher as C

FIXTURE_BUILD = 208784
FIXTURE_DIR = os.path.join(ROOT, "tests", "fixtures", str(FIXTURE_BUILD))
IMAGE_SHA256 = "4a220846c8136dac90380ad0545304d6622a84cf6b0d45a46014212125c4a64d"

STREAM_0264 = bytes.fromhex("640286240200016402ab24010001")
PLAINTEXT_011F = bytes.fromhex("1f01888f0101")


def state_json(state):
    i, j, sbox = state
    return {"i": f"{i:x}", "j": f"{j:x}", "sboxHex": bytes(sbox).hex()}


def frame_raw(payload):
    return bytes([0, 0, len(payload) & 0xFF, (len(payload) >> 8) & 0xFF]) + payload


def wire_fixture(name, direction, **fields):
    body = {
        "build": FIXTURE_BUILD,
        "buildLabel": str(FIXTURE_BUILD),
        "imageSha256": IMAGE_SHA256,
        "kind": "synthetic",
        "representation": "wire-bytes",
        "direction": direction,
        "provenance": (f"Generated by tools/re/MakeSyntheticFixtures.py from the recovered {FIXTURE_BUILD} "
                       "schema and transport cipher."),
        "noClaim": ("Synthetic bytes. They exercise the codec implementation and do not confirm the "
                    "protocol, the captured wire, or live-server compatibility."),
    }
    body.update(fields)
    out = os.path.join(FIXTURE_DIR, name)
    with open(out, "w", newline="\n") as f:
        json.dump(body, f, indent=2, sort_keys=True)
        f.write("\n")
    return out


def main():
    os.makedirs(FIXTURE_DIR, exist_ok=True)

    st, _ = C.key_schedule(bytes(range(20)))
    frame = frame_raw(STREAM_0264)
    wire = C.crypt_stream(st, frame)
    p = wire_fixture("0x264-wire.json", "ServerToClient",
                     transportFrameHex=frame.hex(),
                     wireHex=wire.hex(),
                     cipherState=state_json(C.key_schedule(bytes(range(20)))[0]))
    print("wrote", p)

    st, _ = C.key_schedule(bytes(range(1, 21)))
    wire = C.crypt_stream(st, PLAINTEXT_011F)
    p = wire_fixture("outbound-0x11f.json", "ClientToServer",
                     plaintextHex=PLAINTEXT_011F.hex(),
                     wireHex=wire.hex(),
                     cipherState=state_json(C.key_schedule(bytes(range(1, 21)))[0]))
    print("wrote", p)

    for name in ("0x264-wire.json", "outbound-0x11f.json"):
        p = os.path.join(FIXTURE_DIR, name)
        print(f"sha256 {name}", hashlib.sha256(open(p, "rb").read()).hexdigest())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
