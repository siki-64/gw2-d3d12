#!/usr/bin/env python3

import argparse
import hashlib
import json
import sys

BLOB_A = bytes.fromhex(
    "a555e45f2976fc5bf22eac8d7bdf3690f27fdbae5abf945e7415b30ea7573595"
    "169813e9ba5da8dbfcd5b8fb64123f099336db32f7be55b4103174f7da580292")
BLOB_B = bytes.fromhex(
    "2b0af7caf871425da993b15df860cffa12ba62b83026bf34bd4961ae5b320480"
    "f94f379241477393101615e4e4de95195d0d56eb99929642f22caa87c0768b10")

P = int.from_bytes(BLOB_A, "little")
G = int.from_bytes(BLOB_B, "little")

PM_A = 0xbc8f
PM_Q = 0xadc8
PM_MASK = 0x7fffffff
XOR_SEED = 0x75bd924


def _limbs(raw):
    return [int.from_bytes(raw[i:i + 4].ljust(4, b"\x00"), "little")
            for i in range(0, len(raw), 4)]


def park_miller_expand(seed, bits=512):
    words = bits >> 5
    S = _limbs(seed)
    size = len(S)
    while size > 0 and S[size - 1] == 0:
        size -= 1
    if size == 0:
        S = [0]
        size = 1

    out = []
    idx = 0
    for k in range(words):
        x = (XOR_SEED if k == idx else 0) ^ S[idx]
        word = 0
        for step in range(2):
            x = ((x // PM_Q) + x * PM_A) & 0xFFFFFFFF
            state = x & PM_MASK
            word |= (x & 0xFFFF) << (16 * step)
            x = state
        out.append(word & 0xFFFFFFFF)
        S[idx] = state
        idx = (idx + 1) % size

    return int.from_bytes(b"".join(w.to_bytes(4, "little") for w in out), "little")


def derive(seed):
    R = park_miller_expand(seed)
    return R, pow(G, R, P), pow(4, R, P)


def derived_key(seed, key_len=20):
    return derive(seed)[1].to_bytes(64, "little")[:key_len]


def selftest():
    errors = []
    seed = bytes.fromhex("000102030405060708090a0b0c0d0e0f10111213")
    R, outA, outB = derive(seed)
    if R.bit_length() > 512:
        errors.append("R exceeds 512 bits")
    if outA != pow(G, R, P) or outB != pow(4, R, P):
        errors.append("modpow mismatch")
    if park_miller_expand(seed) != R:
        errors.append("expand not deterministic")
    words = []
    S = _limbs(seed)
    size = len(S)
    while size > 1 and S[size - 1] == 0:
        size -= 1
    idx = 0
    for k in range(16):
        x = ((XOR_SEED if k == idx else 0) ^ S[idx])
        acc = 0
        for step in range(2):
            x = ((x // PM_Q) + x * PM_A) & 0xFFFFFFFF
            acc |= (x & 0xFFFF) << (16 * step)
            x &= PM_MASK
        words.append(acc)
        S[idx] = x
        idx = (idx + 1) % size
    R2 = int.from_bytes(b"".join(w.to_bytes(4, "little") for w in words), "little")
    if R2 != R:
        errors.append("independent recomputation disagrees")
    for s in (bytes(20), bytes.fromhex("ff" * 20), bytes(range(19)) + b"\x00"):
        derive(s)
    if pow(G, R, P) != outA:
        errors.append("outA relation broken")
    return errors


def emit_fixture(path, captured_seed=None, captured_outA=None):
    if (captured_seed is None) != (captured_outA is None):
        raise ValueError("captured_seed and captured_outA must be given together")
    seeds = [
        "000102030405060708090a0b0c0d0e0f10111213",
        "0000000000000000000000000000000000000000",
        "ffffffffffffffffffffffffffffffffffffffff",
    ]
    vectors = []
    for s in seeds:
        R, outA, outB = derive(bytes.fromhex(s))
        vectors.append({
            "seed": s,
            "R": f"{R:0128x}",
            "outA": outA.to_bytes(64, "little").hex(),
            "outB": outB.to_bytes(64, "little").hex(),
        })
    body = {
        "algorithm": "R=park_miller_expand(seed,512); outA=G^R mod P; outB=4^R mod P",
        "build": 208784,
        "buildLabel": "208784",
        "imageSha256": "4a220846c8136dac90380ad0545304d6622a84cf6b0d45a46014212125c4a64d",
        "kind": "synthetic",
        "representation": "wire-bytes",
        "modulusP": BLOB_A.hex(),
        "generatorG": BLOB_B.hex(),
        "noClaim": ("Synthetic reference vectors. They test an implementation of the "
                    "reconstruction and do not confirm the client's output; that needs a "
                    "captured (seed, outA) pair. The seed is fresh client entropy and is "
                    "not on the wire, so a bare capture cannot be decrypted from this. "
                    "The DH group is build-local."),
        "provenance": "Generated by tools/re/Gw2HandshakeKdf.py from the static "
                      "reconstruction in the schema re-derivation.",
        "vectors": vectors,
    }
    if captured_seed is not None:
        body["kind"] = "synthetic+captured"
        body["capturedVector"] = {
            "seed": captured_seed,
            "outA20": captured_outA,
            "note": ("Live (seed, outA[0:20]) pair from one 208784 game-server handshake "
                     "recorded by Gw2.LiveLogin; the server accepted the key, which confirms "
                     "the group and the park_miller_expand derive. The seed is one session's "
                     "client entropy."),
        }
    blob = (json.dumps(body, indent=2) + "\n").encode()
    body["sha256"] = hashlib.sha256(blob).hexdigest()
    with open(path, "w", newline="\n") as f:
        f.write(json.dumps(body, indent=2) + "\n")
    return path


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--selftest", action="store_true")
    ap.add_argument("--seed", metavar="HEX", help="20-byte seed (<=40 hex chars)")
    ap.add_argument("--outA", metavar="HEX",
                    help="expected outA[0:20] from a capture, for comparison")
    ap.add_argument("--emit-fixture", metavar="PATH",
                    help="write synthetic vectors as JSON")
    ap.add_argument("--captured-seed", metavar="HEX",
                    help="live 20-byte seed to embed as capturedVector")
    ap.add_argument("--captured-outA", metavar="HEX",
                    help="live outA[0:20] to embed as capturedVector")
    args = ap.parse_args()

    if args.emit_fixture:
        print("wrote", emit_fixture(args.emit_fixture, args.captured_seed,
                                    args.captured_outA))
        return 0

    if args.selftest:
        errors = selftest()
        for e in errors:
            print("FAIL", e)
        if errors:
            return 1
        print("OK Gw2HandshakeKdf selftest")
        return 0

    if not args.seed:
        ap.print_help()
        return 0

    seed = bytes.fromhex(args.seed)
    R, outA, outB = derive(seed)
    print("R       ", f"{R:0128x}")
    print("outA    ", outA.to_bytes(64, "little").hex())
    print("outB    ", outB.to_bytes(64, "little").hex())
    print("conn+118", derived_key(seed).hex())
    if args.outA:
        expected = bytes.fromhex(args.outA)
        got = derived_key(seed)
        print("match   ", got == expected)
        return 0 if got == expected else 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
